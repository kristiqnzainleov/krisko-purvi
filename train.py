def vary(text, is_question, typos=True):
    """Прави от една формулировка много подобни: обръщения, пунктуация, правописни грешки."""
    prefixes = ["", "", "", "", "", "ей ", "а ", "хей ", "криско ", "криско, ", "е ", "ами ", "и ", "я ",
                "добре ", "окей ", "хайде ", "а ти ", "е ти "]
    if is_question:
        prefixes += ["кажи ", "кажи ми ", "я кажи ", "я ми кажи ", "моля те кажи ", "а кажи ", "моля те ",
                     "кажи ми моля те ", "можеш ли да ми кажеш ", "искам да знам ", "знаеш ли ", "я ми кажи "]
    suffixes = ["", "", "", "", "", " бе", " криско", ", криско", " моля", " де", " ти", " приятел",
                " приятелю", " човече", " брат", " при теб", " днес", " сега", " на теб"]
    words = text.split()
    if typos and len(words) > 1 and random.random() < 0.3:     # излишна думичка по средата
        words.insert(random.randint(1, len(words) - 1),
                     random.choice(["точно", "ти", "сега", "всъщност", "пък", "май", "тогава", "бе", "твоят", "човек"]))
    text = random.choice(prefixes) + " ".join(words) + random.choice(suffixes)
    if typos and random.random() < 0.2 and len(text) > 3:      # правописна грешка
        i = random.randrange(len(text) - 1)
        kind = random.random()
        if kind < 0.4:
            text = text[:i] + text[i + 1:]                           # изпусната буква
        elif kind < 0.7:
            text = text[:i] + text[i + 1] + text[i] + text[i + 2:]   # разменени букви
        else:
            text = text[:i] + text[i] + text[i:]                     # двойна буква
    marks = ["", "", "?", "?", "??", "!", "."] if is_question else ["", "", "", "!", "!!", ".", "?", "..."]
    return (text + random.choice(marks))[:60]


