    result = compute(a, b)
    draft = ("-" if result < 0 else "") + str(abs(result))[::-1]
    if said == result:
        return f"[{draft}]Не съм сгрешил. {a} {word} {b} наистина е {result}."
    return f"[{draft}]{SORRY}{a} {word} {b} е {result}."


