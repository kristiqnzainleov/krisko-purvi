def fix_score(cases):
    """cases: (въпрос, казан отговор, очакван отговор на "грешно е")"""
    wrong = [(q, said, got) for q, said, want in cases for got in [ask("грешно е", (q, said))] if got != want]
    return len(cases) - len(wrong), len(cases), wrong[:2]


