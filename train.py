# ---- 2. Токенизатор: по един токен на символ -------------------------------
config = dict(dim=128, layers=4, heads=4, block_size=256)
all_text = "".join(q + a + (ctx[0] + ctx[1] if ctx else "") for ctx, q, a in examples)
if CONTINUE:
    model, tokenizer = load("model")                   # продължаваме от сегашния модел и неговия речник
    missing = set(all_text) - set(tokenizer.itos)
    assert not missing, f"Нови символи {missing}: пусни пълно обучение без --continue"
else:
    tokenizer = CharTokenizer.from_texts([all_text, LETTERS])
    model = TinyLM(len(tokenizer), **config)


def encode_prompt(q, ctx=None):
    """<user>предишен въпрос<bot>предишен отговор<user>въпрос<bot>"""
    before = [tokenizer.user] + tokenizer.encode(ctx[0]) + [tokenizer.bot] + tokenizer.encode(ctx[1]) if ctx else []
    return before + [tokenizer.user] + tokenizer.encode(q) + [tokenizer.bot]


inputs, targets = [], []
for ctx, q, a in examples:
    question = encode_prompt(q, ctx)
    answer = tokenizer.encode(a) + [tokenizer.eos]
    row = question + answer
    if len(row) > config["block_size"]:
        continue
    pad = config["block_size"] - len(row)
    inputs.append(row[:-1] + [tokenizer.pad] * (pad + 1))
    # Учим само отговора: върху въпроса и празното място няма оценка (-100).
    targets.append([-100] * (len(question) - 1) + answer + [-100] * (pad + 1))
device = "mps" if torch.backends.mps.is_available() else "cpu"   # GPU-то на Mac, ако го има
inputs, targets = torch.tensor(inputs, device=device), torch.tensor(targets, device=device)
lengths = (inputs != tokenizer.pad).sum(1)

# ---- 3. Модел ---------------------------------------------------------------
model = model.to(device)
print(f"Устройство: {device}  примери: {len(inputs)}  символи в речника: {len(tokenizer)}  параметри: {model.num_parameters():,}", flush=True)

# ---- 4. Обучение ------------------------------------------------------------
STEPS, BATCH, LR = (2500, 128, 5e-4) if CONTINUE else (int(os.environ.get("STEPS", 12000)), 128, 1.5e-3)
opt = torch.optim.AdamW(model.parameters(), lr=LR)
model.train()
for step in range(1, STEPS + 1):
    for group in opt.param_groups:                     # скоростта на учене плавно намалява
        group["lr"] = LR * min(1.0, step / 100) * (0.05 + 0.95 * 0.5 * (1 + math.cos(math.pi * step / STEPS)))
    # Взимаме повече примери и от тях избираме близки по дължина, за да няма много празно място.
    pool = torch.randint(0, len(inputs), (BATCH * 6,), device=device)
    pool = pool[lengths[pool].argsort()]
    start = int(torch.randint(0, BATCH * 5 + 1, (1,)))
    pick = pool[start:start + BATCH]
    width = int(lengths[pick].max())
    loss = model.loss(inputs[pick, :width], targets[pick, :width])
    loss.backward()
    torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
    opt.step()
    opt.zero_grad()
    if step % 1000 == 0:
        print(f"стъпка {step:4d}  loss {loss.item():.4f}", flush=True)

# ---- 5. Запис ---------------------------------------------------------------
model.eval().cpu()
save(model, tokenizer, "model", **config)
